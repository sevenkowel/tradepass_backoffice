// ==================== 辅助函数 ====================

export function getProductBySymbol(symbol: string): TradingProduct | undefined {
  return mockProducts.find(p => p.symbol === symbol);
}

export function getProductDetail(symbol: string): ProductDetail | undefined {
  return mockProductDetails[symbol] || undefined;
}

export function getProductsByClass(assetClass: AssetClass): TradingProduct[] {
  return mockProducts.filter(p => p.assetClass === assetClass);
}

export function getFavoriteProducts(): TradingProduct[] {
  return mockProducts.filter(p => p.isFavorite);
}
